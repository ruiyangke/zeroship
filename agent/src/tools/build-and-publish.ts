/**
 * build_and_publish — one-shot tool that takes a built Vite project
 * and ships it to the platform. Hides the awkward wrapping step
 * (reading hashed-filename dist/assets/* and inlining them as
 * template literals) which the LLM struggles with for non-trivial
 * bundle sizes.
 *
 * Steps:
 *   1. Verify dist/ exists in the sandbox (run vite build first if not).
 *   2. Walk dist/ on the host (sandbox bind-mount) — fast + simple.
 *   3. Upload every dist/<file> to the control plane as a static asset
 *      (PUT /api/apps/:id/assets/<path>).
 *   4. Deploy a tiny ES-module fetch handler that returns 404 for any
 *      unknown path. The gateway's static-asset fallback (and SPA
 *      index.html fallback) handles everything else.
 *
 * Returns a JSON status with the public preview URL.
 */
import { tool } from "@langchain/core/tools";
import { z } from "zod";
import * as fs from "node:fs/promises";
import * as path from "node:path";
import { CONTROL_URL, CONTROL_KEY, GATEWAY_URL } from "../env.js";
import {
  execCommand,
  getSession,
  createOrAttachSession,
} from "../sandbox.js";

// Minimal fetch handler — every request returns 404 unless the
// gateway's static-asset path matches first. A bare 200 root is
// useful for healthchecks.
const STUB_SERVER = `// Auto-generated by build_and_publish.
// Static assets are served by the gateway directly from the
// control plane's VFS; this handler exists only so the route
// registry recognizes the app as live.
export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    if (url.pathname === "/__health") {
      return new Response("ok", { status: 200 });
    }
    return new Response("Not Found", { status: 404 });
  },
};
`;

interface UploadResult {
  uploaded: string[];
  skipped: string[];
  errors: string[];
}

async function walkDir(root: string, base = ""): Promise<string[]> {
  const out: string[] = [];
  const entries = await fs.readdir(path.join(root, base), { withFileTypes: true });
  for (const e of entries) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) {
      out.push(...await walkDir(root, rel));
    } else if (e.isFile()) {
      out.push(rel);
    }
  }
  return out;
}

async function uploadAsset(
  appId: string,
  assetPath: string,
  body: Buffer,
  contentType: string,
): Promise<void> {
  const url = `${CONTROL_URL}/api/apps/${appId}/assets/${encodeURI(assetPath)}`;
  const res = await fetch(url, {
    method: "PUT",
    headers: {
      Authorization: `Bearer ${CONTROL_KEY}`,
      "Content-Type": contentType,
    },
    body,
  });
  if (!res.ok) {
    throw new Error(`PUT ${assetPath} → ${res.status}: ${(await res.text()).slice(0, 200)}`);
  }
}

/** Look up the app or create it if it doesn't exist. Returns the
 *  resolved app_id (which may differ from the requested one if we
 *  had to create — the control plane assigns its own UUID). */
async function ensureApp(requestedId: string, fallbackName: string): Promise<{ app_id: string; app_name: string }> {
  // 1. Try GET — UUID exists?
  const getRes = await fetch(`${CONTROL_URL}/api/apps/${requestedId}`, {
    headers: { Authorization: `Bearer ${CONTROL_KEY}` },
  });
  if (getRes.ok) {
    const app = await getRes.json();
    return { app_id: app.id, app_name: app.name };
  }
  // Treat both 404 (UUID valid, app missing) and 400 (UUID invalid)
  // as "go create one" — the requested id was a placeholder.
  if (getRes.status !== 404 && getRes.status !== 400) {
    throw new Error(`get app: ${getRes.status} ${(await getRes.text()).slice(0, 200)}`);
  }

  // 2. Not found — create. The control plane assigns its own UUID
  //    (we can't request a specific one), so the returned id will
  //    differ from `requestedId`. We rely on the caller to use the
  //    returned id from here on.
  const createRes = await fetch(`${CONTROL_URL}/api/apps`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${CONTROL_KEY}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ name: fallbackName, plan_id: "free" }),
  });
  if (!createRes.ok) {
    throw new Error(`create app: ${createRes.status} ${(await createRes.text()).slice(0, 200)}`);
  }
  const app = await createRes.json();
  return { app_id: app.id, app_name: app.name };
}

function contentTypeFor(p: string): string {
  const ext = p.split(".").pop()?.toLowerCase() ?? "";
  switch (ext) {
    case "html": return "text/html; charset=utf-8";
    case "css":  return "text/css; charset=utf-8";
    case "js": case "mjs": return "application/javascript; charset=utf-8";
    case "json": return "application/json; charset=utf-8";
    case "svg":  return "image/svg+xml";
    case "png":  return "image/png";
    case "jpg": case "jpeg": return "image/jpeg";
    case "ico":  return "image/x-icon";
    case "woff": return "font/woff";
    case "woff2": return "font/woff2";
    case "txt":  return "text/plain; charset=utf-8";
    case "map":  return "application/json; charset=utf-8";
    default:     return "application/octet-stream";
  }
}

export const buildAndPublish = tool(
  async ({ project_id, app_id, app_name, session_id, build_first }) => {
    // Resolve the sandbox session. Two valid call shapes:
    //   1. session_id passed directly (caller already opened one)
    //   2. project_id passed — we open-or-attach idempotently
    // (The deepagents backend opens sessions implicitly per chat,
    // so the agent typically only knows the project_id.)
    let session;
    try {
      if (session_id) {
        session = await getSession(session_id);
      } else if (project_id) {
        session = await createOrAttachSession(project_id);
      } else {
        return JSON.stringify({
          ok: false,
          error: "must pass either session_id or project_id",
        });
      }
    } catch (e: any) {
      return JSON.stringify({ ok: false, error: `resolve session: ${e?.message ?? e}` });
    }

    // Ensure the target app exists (create it if not). Note: the
    // control plane assigns its own UUID on create, so the resolved
    // id may differ from the requested one. We use the resolved id
    // from here on.
    let resolved;
    try {
      // Sensible default name if none was provided.
      const fallbackName = app_name?.trim() || `app-${session.project_id.slice(0, 8)}`;
      resolved = await ensureApp(app_id, fallbackName);
    } catch (e: any) {
      return JSON.stringify({ ok: false, error: `ensure app: ${e?.message ?? e}` });
    }
    const realAppId = resolved.app_id;
    const realAppName = resolved.app_name;

    // Optionally run `npm run build` first so the agent doesn't have
    // to remember to do it. Cheap if dist/ is up-to-date.
    if (build_first !== false) {
      const r = await execCommand(session.session_id, "npm run build", { timeoutMs: 180_000 });
      if (r.status !== 0) {
        return JSON.stringify({
          ok: false,
          error: `npm run build failed (status ${r.status}): ${r.stderr.slice(0, 800)}`,
        });
      }
    }

    const distDir = path.join(session.workspace_path, "dist");
    let stat;
    try {
      stat = await fs.stat(distDir);
      if (!stat.isDirectory()) throw new Error("not a directory");
    } catch (e: any) {
      return JSON.stringify({
        ok: false,
        error: `dist/ missing: ${e?.message ?? e}. Run npm run build first or set build_first=true.`,
      });
    }

    let files: string[];
    try {
      files = await walkDir(distDir);
    } catch (e: any) {
      return JSON.stringify({ ok: false, error: `walk dist/: ${e?.message ?? e}` });
    }

    if (files.length === 0) {
      return JSON.stringify({ ok: false, error: "dist/ is empty after build" });
    }

    const result: UploadResult = { uploaded: [], skipped: [], errors: [] };

    for (const rel of files) {
      const full = path.join(distDir, rel);
      try {
        const stat = await fs.stat(full);
        if (stat.size > 8 * 1024 * 1024) {
          result.skipped.push(`${rel} (>8MB)`);
          continue;
        }
        const body = await fs.readFile(full);
        await uploadAsset(realAppId, rel, body, contentTypeFor(rel));
        result.uploaded.push(`${rel} (${stat.size}b)`);
      } catch (e: any) {
        result.errors.push(`${rel}: ${e?.message ?? e}`);
      }
    }

    if (result.errors.length > 0) {
      return JSON.stringify({
        ok: false,
        error: "asset upload errors",
        ...result,
      });
    }

    // Deploy the stub server so the route registry knows the app is live.
    const deployRes = await fetch(`${CONTROL_URL}/api/apps/${realAppId}/deploy`, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${CONTROL_KEY}`,
        "Content-Type": "application/javascript",
      },
      body: STUB_SERVER,
    });
    if (!deployRes.ok) {
      return JSON.stringify({
        ok: false,
        error: `deploy stub failed: ${deployRes.status} ${(await deployRes.text()).slice(0, 200)}`,
        ...result,
      });
    }
    const deployData = await deployRes.json();

    return JSON.stringify({
      ok: true,
      app_id: realAppId,
      app_name: realAppName,
      uploaded: result.uploaded,
      skipped: result.skipped,
      deploy_hash: deployData.deploy_hash,
      preview_url: `${GATEWAY_URL}/apps/${realAppName}/`,
      message:
        "Built and published. The static assets and stub server are live. " +
        "The dashboard's preview iframe will reload automatically.",
    });
  },
  {
    name: "build_and_publish",
    description:
      "Build the project (vite build) and publish it to the platform in one shot. Reads every file from dist/ and uploads them as static assets, then deploys a minimal fetch handler that lets the gateway serve them. Auto-creates the target app if app_id doesn't exist yet. Use this instead of trying to inline JS bundles into a deploy_app call.",
    schema: z.object({
      project_id: z.string().min(1).max(64).optional()
        .describe("Project id (typically the workspace context's app_id). The tool opens or re-attaches the matching sandbox session. Pass this OR session_id."),
      session_id: z.string().uuid().optional()
        .describe("Sandbox session UUID. Only needed if you have one in hand; usually project_id is enough."),
      app_id: z.string().uuid()
        .describe("Target zeroship app UUID. If it doesn't exist yet, the tool creates it under app_name."),
      app_name: z.string().min(1).max(64).regex(/^[a-zA-Z0-9_-]+$/).optional()
        .describe("Slug to use if the app needs to be created (defaults to a derivation from project_id)."),
      build_first: z.boolean().optional().default(true)
        .describe("Run `npm run build` before publishing (default true). Set false if you just built."),
    }),
  },
);
