#[compio::test]
async fn supports_serial_and_rejects_a_column_without_an_owned_sequence() {
    let url = skip_if_no_pg!();
    let session = PgDevSession::connect(&url);
    let cfg = cfg_for(&token());
    setup(&session, &cfg).await;
    session
        .batch(&format!(
            "CREATE TABLE \"{}\".serial_items (id bigserial PRIMARY KEY);
             INSERT INTO \"{}\".serial_items (id) VALUES (41);
             CREATE TABLE \"{}\".plain_items (id bigint PRIMARY KEY)",
            cfg.project_schema, cfg.project_schema, cfg.project_schema
        ))
        .await
        .expect("create serial and unowned fixtures");

    assert!(run(&session, &cfg, step("serial_items"))
        .await
        .expect("synchronize serial sequence"));
    assert_eq!(
        next_value(&session, &cfg.project_schema, "serial_items", "id").await,
        42
    );

    let error = run(&session, &cfg, step("plain_items"))
        .await
        .expect_err("plain bigint must be rejected");
    assert!(error
        .to_string()
        .contains("no owned PostgreSQL identity/serial sequence"));
    cleanup(&session, &cfg).await;
}
