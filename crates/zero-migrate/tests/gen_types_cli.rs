#![cfg(feature = "zsv8")]
//! **Migration-first P3 — the `gen-types` load/emit/check round-trip.**
//!
//! Pre-change, `load_dir_ops` required committed `<stem>.ir.json` siblings and a
//! `.ts`-only migrations dir could not generate types. Post-change, gen-types
//! records each committed `.ts` through the sandboxed recorder, folds the transient
//! IR in memory, and emits byte-identical `env.db.ts` + `schema.runtime.json`.

use std::path::Path;

use zero_migrate::frontend::recorder_service::recorder_child_path;
use zero_migrate::frontend::{
    check_artifacts, load_dir_ops, render_artifacts, write_artifacts, ENV_DTS_FILE,
    RUNTIME_DESCRIPTOR_FILE,
};

const CREATE_USERS_TS: &str = r#"
import { table, t } from "@zeroship/migrate";

export function up() {
  table("users").create({
    columns: {
      email: t.text().notNull().unique(),
    },
  });
}
"#;

const ADD_BIO_TS: &str = r#"
import { table, t } from "@zeroship/migrate";

export function up() {
  table("users").column("bio").add({ type: t.text() });
}
"#;

const EXPECTED_ENV_DB_TS: &str = r#"// GENERATED by `zero-migrate-js gen-types` — DO NOT EDIT.
//
// The typed `env.db` surface, reconstructed from the op.* migration set
// (migration-first: the migrations are the source of truth, types are
// generated from the fold). Re-run `gen-types` after migration changes; the
// `gen-types --check` CI gate fails if this file drifts from the migrations.
//
// The schema below is a reconstruction of `@zeroship/db` `t.*()` builder
// calls — NOT a hand-rolled interface — so it flows through the SAME
// `InferSchema`/`Row`/`Collections`/`Db`/`Id<>`/`MaskedValue<>` inference
// chain a declared schema would.
import { t, schema as defineSchema, type Db } from "@zeroship/db";

const schema = {
  users: defineSchema({
    id: t.string().required(),
    created_at: t.timestamp().required(),
    updated_at: t.timestamp().required(),
    created_by: t.string(),
    updated_by: t.string(),
    version: t.number().required(),
    deleted_at: t.timestamp(),
    email: t.string().required().unique(),
    bio: t.string(),
  }).uniqueIndex("users_email_key", ["email"]).index("users_deleted_at_idx", ["deleted_at"]).index("users_updated_at_idx", ["updated_at"]).index("users_created_by_idx", ["created_by"]),
} as const;

declare module "zeroship" {
  interface Env {
    db: Db<typeof schema>;
  }
}

export {};
"#;

