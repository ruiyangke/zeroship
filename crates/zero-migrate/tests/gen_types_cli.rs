fn assert_child_built() {
    let bin = recorder_child_path();
    assert!(
        bin.exists(),
        "recorder child binary missing at {} — run `cargo build -p zero-migrate --bins` first",
        bin.display()
    );
}

fn write_migration_ts(dir: &Path, stem: &str, source: &str) {
    std::fs::write(dir.join(format!("{stem}.ts")), source.as_bytes()).unwrap();
}

#[test]
fn gen_types_round_trips_from_ts_only_dir_with_byte_identical_output() {
    assert_child_built();
    let dir = tempfile::tempdir().unwrap();
    write_migration_ts(dir.path(), "20240101090000_create_users", CREATE_USERS_TS);
    write_migration_ts(dir.path(), "20240101100000_add_bio", ADD_BIO_TS);

    let ops = load_dir_ops(dir.path()).expect("load .ts-only migrations via transient recorder");
    assert_eq!(ops.len(), 2, "both migrations' ops concatenated in version order");
    assert!(
        !dir.path().join("20240101090000_create_users.ir.json").exists(),
        "gen-types must not write a committed .ir.json"
    );
    assert!(
        !dir.path().join("20240101100000_add_bio.ir.json").exists(),
        "gen-types must not write a committed .ir.json"
    );

    let artifacts = render_artifacts(&ops, "public").expect("render");
    assert_eq!(artifacts.env_dts, EXPECTED_ENV_DB_TS);
    assert_eq!(artifacts.runtime_descriptor, EXPECTED_RUNTIME_DESCRIPTOR);

    let out = tempfile::tempdir().unwrap();
    write_artifacts(out.path(), &artifacts).expect("write artifacts");
    assert!(out.path().join(RUNTIME_DESCRIPTOR_FILE).exists());
    assert!(out.path().join(ENV_DTS_FILE).exists());
    check_artifacts(out.path(), &artifacts).expect("freshly-written artifacts are in sync");
}

#[test]
fn gen_types_check_trips_on_generated_artifact_drift() {
    assert_child_built();
    let dir = tempfile::tempdir().unwrap();
    write_migration_ts(dir.path(), "20240101090000_create_users", CREATE_USERS_TS);
    let ops = load_dir_ops(dir.path()).expect("load");
    let artifacts = render_artifacts(&ops, "public").expect("render");

    let out = tempfile::tempdir().unwrap();
    write_artifacts(out.path(), &artifacts).expect("write");

    // Corrupt the generated env.db.ts (simulate a stale, hand-edited artifact).
    let dts_path = out.path().join(ENV_DTS_FILE);
    let mut stale = std::fs::read_to_string(&dts_path).unwrap();
    stale.push_str("\n// drift\n");
    std::fs::write(&dts_path, stale).unwrap();

    let err = check_artifacts(out.path(), &artifacts).expect_err("drift must trip --check");
    let msg = err.to_string();
    assert!(msg.contains("STALE") || msg.contains("env.db.ts"), "drift names the file: {msg}");
}

#[test]
fn gen_types_check_missing_generated_artifact_is_an_error() {
    assert_child_built();
    let dir = tempfile::tempdir().unwrap();
    write_migration_ts(dir.path(), "20240101090000_create_users", CREATE_USERS_TS);
    let ops = load_dir_ops(dir.path()).expect("load");
    let artifacts = render_artifacts(&ops, "public").expect("render");

    let out = tempfile::tempdir().unwrap();
    let err = check_artifacts(out.path(), &artifacts).expect_err("missing generated artifact");
    assert!(err.to_string().contains("missing"), "names the missing file: {err}");
}
